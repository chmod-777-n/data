#include <stdio.h>

#define SIZE 15 // Размер должен быть нечетным, чтобы был четкий центр

int main(void) {
    char matrix[SIZE][SIZE];
    
    // Заполняем матрицу пробелами
    for (int i = 0; i < SIZE; i++) {
        for (int j = 0; j < SIZE; j++) {
            matrix[i][j] = ' ';
        }
    }

    // Стартуем строго из центра
    int y = SIZE / 2;
    int x = SIZE / 2;
    matrix[y][x] = '*';

    // Направления движения: вправо, вниз, влево, вверх
    int dx[] = {1, 0, -1, 0};
    int dy[] = {0, 1, 0, -1};
    
    int dir = 0;         // Текущее направление (индекс в массивах dx/dy)
    int step_size = 2;   // Длина шага (через 2 клетки, чтобы витки не сливались)

    // Крутим спираль, пока не выйдем за границы
    while (x >= 0 && x < SIZE && y >= 0 && y < SIZE) {
        
        // Делаем линию в текущем направлении
        for (int i = 0; i < step_size; i++) {
            x += dx[dir];
            y += dy[dir];
            
            // Защита от выхода за массив без if (используем логическое И)
            (x >= 0 && x < SIZE && y >= 0 && y < SIZE) && (matrix[y][x] = '*');
        }

        // Меняем направление на следующее (по кругу: 0, 1, 2, 3, 0...)
        dir = (dir + 1) % 4;

        // Каждые два поворота (после движения влево и после движения вверх) 
        // увеличиваем длину шага на 2, чтобы спираль расширялась
        step_size += (dir % 2 == 0) * 2;
    }

    // Выводим результат
    for (int i = 0; i < SIZE; i++) {
        for (int j = 0; j < SIZE; j++) {
            printf("%c ", matrix[i][j]);
        }
        printf("\n");
    }

    return 0;
}
